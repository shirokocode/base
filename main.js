let pairingNumber = null

async function getPairingNumber() {
    if (pairingNumber) return pairingNumber
    let num = String(global.pairingNumber || '').replace(/\D/g, '')
    // format internasional: 6-15 digit, tidak diawali 0
    while (!/^[1-9]\d{5,14}$/.test(num)) {
        if (num) console.log(chalk.red('Nomor harus format internasional tanpa 0 di depan, contoh: 6281234567890'))
        num = (await ask(chalk.cyan('Masukkan nomor WhatsApp bot (contoh 6281234567890): '))).replace(/\D/g, '')
    }
    return (pairingNumber = num)
}

async function requestPairing(hsin) {
    const number = await getPairingNumber()
    for (let attempt = 0; attempt < 2; attempt++) {
        try {
            const code = await hsin.requestPairingCode(number)
            console.log(chalk.black(chalk.bgGreen(' KODE PAIRING ')), chalk.bold(String(code).match(/.{1,4}/g).join('-')))
            console.log('Buka WhatsApp > Perangkat Tertaut > Tautkan Perangkat > Tautkan dengan nomor telepon, lalu masukkan kode di atas.')
            return
        } catch (e) {
            if (e && e.output && e.output.statusCode === 409) {   // masih ada kode yang menggantung
                hsin.cancelPairingCode()
                continue
            }
            console.log(chalk.red(`Gagal meminta kode pairing: ${e.message}${e.data ? ` (${e.data})` : ''}`))
            return
        }
    }
}

